pub fn is_git_option(arg: &str) -> bool {
    let Some(rest) = arg.strip_prefix("--") else {
        return false;
    };
    let name = rest.split_once('=').map_or(rest, |(n, _)| n);
    LONG.binary_search(&name).is_ok()
        || name
            .strip_prefix("no-")
            .is_some_and(|n| LONG.binary_search(&n).is_ok())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn list_is_sorted_and_matches_forms() {
        assert!(LONG.windows(2).all(|w| w[0] < w[1]));
        assert!(is_git_option("--show-signature"));
        assert!(is_git_option("--no-notes"));
        assert!(is_git_option("--format=%h"));
        assert!(!is_git_option("--bogus"));
        assert!(!is_git_option("-Z"));
    }
}
